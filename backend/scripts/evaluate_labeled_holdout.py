"""Evaluate independently adjudicated holdout JSONL; never infer labels or predictions."""
from __future__ import annotations
import argparse, csv, json
from pathlib import Path
POSITIVE = {"phishing", "credential_harvesting", "bec_payment_change", "bec", "malware", "malicious", "positive"}
NEGATIVE = {"benign_legitimate", "benign", "legitimate", "ham", "negative"}
REVIEWED = {"approved", "adjudicated", "reviewed"}
def read_rows(path: Path):
    rows = []
    for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip(): continue
        try: row = json.loads(line)
        except json.JSONDecodeError as exc: raise ValueError(f"Invalid JSONL line {line_no}: {exc}") from exc
        if not isinstance(row, dict): raise ValueError(f"Line {line_no} must be a JSON object")
        rows.append(row)
    return rows
def evaluate(rows):
    tp = fp = tn = fn = excluded_unreviewed = excluded_nonbinary = 0
    output_rows = []
    for row in rows:
        expected = str(row.get("expected_label") or "").strip().lower()
        predicted = str(row.get("predicted_label") or "").strip().lower()
        review = str(row.get("independent_review_status") or "").strip().lower()
        if expected not in POSITIVE | NEGATIVE or predicted not in POSITIVE | NEGATIVE:
            excluded_nonbinary += 1; reason = "missing_or_nonbinary_label"
        elif review not in REVIEWED:
            excluded_unreviewed += 1; reason = "awaiting_independent_review"
        else:
            actual_pos, pred_pos = expected in POSITIVE, predicted in POSITIVE
            if actual_pos and pred_pos: tp += 1
            elif actual_pos: fn += 1
            elif pred_pos: fp += 1
            else: tn += 1
            reason = "scored"
        output_rows.append({**row, "evaluation_status": reason})
    precision = tp / (tp + fp) if tp + fp else None
    recall = tp / (tp + fn) if tp + fn else None
    f1 = 2 * precision * recall / (precision + recall) if precision is not None and recall is not None and precision + recall else None
    fpr = fp / (fp + tn) if fp + tn else None
    scored = tp + fp + tn + fn
    report = {"scope": "independently reviewed holdout only", "holdout_rows_received": len(rows),
        "scored_independently_reviewed": scored, "excluded_unreviewed": excluded_unreviewed,
        "excluded_nonbinary_or_missing": excluded_nonbinary,
        "confusion_matrix": {"tp": tp, "fp": fp, "tn": tn, "fn": fn},
        "precision": precision, "recall": recall, "f1": f1, "false_positive_rate": fpr,
        "accuracy_claim_status": "UNVERIFIED" if scored == 0 else "HOLDOUT_METRICS_ONLY_REQUIRES_REVIEWED_LABELS",
        "limitations": ["No labels or predictions are generated by this evaluator.",
        "Non-binary/inconclusive cases are excluded from binary metrics.",
        "A zero-sample report is not evidence of model accuracy."]}
    return report, output_rows
def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", required=True, type=Path, help="JSONL with expected_label, predicted_label and independent_review_status")
    p.add_argument("--out-prefix", required=True, type=Path)
    args = p.parse_args()
    rows = read_rows(args.input); report, details = evaluate(rows)
    args.out_prefix.parent.mkdir(parents=True, exist_ok=True)
    args.out_prefix.with_suffix(".json").write_text(json.dumps({"metrics": report, "results": details}, indent=2) + "\n", encoding="utf-8")
    fields = sorted({key for row in details for key in row}) or ["fixture_id", "expected_label", "predicted_label", "independent_review_status", "evaluation_status"]
    with args.out_prefix.with_suffix(".csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore"); writer.writeheader(); writer.writerows(details)
    print(json.dumps(report, indent=2))
if __name__ == "__main__": main()
